package dev.penned.app.ui.calendar

import androidx.compose.ui.unit.dp

/**
 * 日历的版式常量（M3-17 优化轮）。
 *
 * 三条都是"一处定义、多处使用"的共享值——网格与收起态的周条用的是同一枚格子，
 * 任何一处都不许自己再写一个 alpha / 比例（否则两处慢慢就漂开了）。
 */
internal object CalendarStyle {

    /**
     * 格子高宽比（`aspectRatio` 是"宽/高"）：**小于 1 才是竖着更长**。
     * 日期一行 + 支/收两行小字要放得下——按 0.92 试过，两行小字会被裁掉半截；0.74 刚好。
     */
    const val cellAspect = 0.74f

    /** 选中态描边：热力已经占了格子的"底"，选中改用品牌色**描边**，两者不抢同一层。 */
    val selectStroke = 2.dp

    /** 格子之间的细缝（每格四周各 2dp，7 列摊在屏边距内）。 */
    val cellGap = 2.dp

    /**
     * 非本月（网格带出的上/下月日子、周条里邻月的日子）**统一变淡的因子**：
     * 整格内容（日期字、支/收小字、热力底、今天圈）乘同一个 alpha。
     *
     * 0.45 是"淡但看得见"的那条线：浅色下日期字 2.89:1、支/收小字 2.28:1（`ContrastTest` 守 2.0）；
     * 这是**刻意的去强调**——真数在选中那天的日头条里，所以不套 4.5:1 门槛
     * （理由写在界面规范 §13·补二十八）。
     */
    const val outOfMonthAlpha = 0.45f
}
